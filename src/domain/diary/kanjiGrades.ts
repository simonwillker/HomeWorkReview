/** 漢字1文字にマッチする（CJK 統合漢字） */
export const KANJI_RE = /[\u4e00-\u9fff]/;

const GRADE_OF = new Map<string, SchoolGrade>();
for (const g of GRADES) {
  for (const ch of KANJI_BY_GRADE[g]) GRADE_OF.set(ch, g);
}

/** 小学校で習う漢字の総数（1026 字） */
export const KYOIKU_KANJI_TOTAL = GRADE_OF.size;

/** その漢字を習う学年。小学校で習わない漢字は undefined */
export function gradeOfKanji(ch: string): SchoolGrade | undefined {
  return GRADE_OF.get(ch);
}

/** 語の中でいちばん後の学年（その語を漢字で書けるようになる学年）。小学校で習わない字が混ざれば undefined */
export function gradeOfWord(word: string): SchoolGrade | undefined {
  let max: SchoolGrade = 1;
  for (const ch of word) {
    if (!KANJI_RE.test(ch)) continue;
    const g = gradeOfKanji(ch);
    if (!g) return undefined;
    if (g > max) max = g;
  }
  return max;
}

